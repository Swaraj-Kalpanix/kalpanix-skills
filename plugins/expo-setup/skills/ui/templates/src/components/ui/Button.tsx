import type { ReactNode } from 'react';
import { StyleSheet, View } from 'react-native';
import { Button as TamaguiButton, Spinner, Theme, useTheme, type GetProps } from 'tamagui';

import { useBrandSolid } from './useBrandSolid';

/**
 * The app's button.
 *
 * Wraps Tamagui's `Button` so the four kinds an app actually needs are named, rather than every screen
 * assembling `theme`, `bg`, `color` and `borderWidth` for itself and drifting apart.
 *
 * | variant | when |
 * |---|---|
 * | `primary` | the one obvious action on a screen — filled, the brand colour |
 * | `secondary` | an alternative action — outlined, neutral. The default |
 * | `ghost` | low emphasis, inside rows and headers |
 * | `destructive` | deletes and cancels — **outlined red, never the brand** |
 *
 * ## Two colour decisions, both measured rather than chosen by eye
 *
 * **The primary fill and label are measured, per scheme** (`BRAND_BUTTON` in `src/theme/brand.ts`, generated by
 * `makeBrandTheme.mjs`). A white label wherever the brand can carry one at AA (4.5:1), the fill deepened just enough —
 * in dark mode a step deeper than the bright step 9 the accents use. The theme's own `$color1` would be near-black in
 * dark mode, which can pass on paper and still read as black on colour. The colours come from `useBrandSolid`, which
 * the brand `IconButton` shares.
 *
 * **`destructive` is outlined, not filled.** A filled Tamagui red cannot carry AA-compliant body text in
 * light mode: `$color1` on red-9 measures **3.84:1** and even pure white only **3.91:1** — both below 4.5,
 * and a button label is not "large text". Red *text* on the page background clears it comfortably. Outlined
 * is also the platform-idiomatic treatment for a destructive action, so the accessible option is the
 * conventional one here rather than a compromise.
 *
 * ## The label colour is resolved, not passed as a token
 *
 * Tamagui forwards a Button's `color` to its `icon` — and an icon is an SVG, which takes a colour *value*. A
 * token string reached it as the literal `"$color12"`, which react-native-svg rejects ("not a valid color"),
 * once per button per render. So each variant renders inside its theme and reads the colour out with
 * `useTheme`; the text and the icon get the same real colour.
 */
export interface AppButtonProps extends Omit<GetProps<typeof TamaguiButton>, 'theme' | 'variant'> {
  variant?: 'primary' | 'secondary' | 'ghost' | 'destructive';
  /** Show a spinner in the icon slot and block presses. The label stays, so the button keeps its width. */
  loading?: boolean;
  children?: ReactNode;
}

export function Button(props: AppButtonProps) {
  const variant = props.variant ?? 'secondary';
  if (variant === 'primary') {
    return (
      <Theme name="brand">
        <ThemedButton {...props} />
      </Theme>
    );
  }
  if (variant === 'destructive') {
    return (
      <Theme name="red">
        <ThemedButton {...props} />
      </Theme>
    );
  }
  return <ThemedButton {...props} />;
}

/** A press settles the button a little — the one thing that animates. */
const PRESSED_SCALE = 0.98;

/** Rendered inside the variant's theme, so `useTheme` returns that theme's colours. */
function ThemedButton({ variant = 'secondary', loading, disabled, children, icon, ...props }: AppButtonProps) {
  const theme = useTheme();
  const solid = useBrandSolid();
  const isLoading = Boolean(loading);

  // 44pt tall and 10pt corners everywhere: the size Tamagui's `$4` gives, with the radius the inputs use, so a
  // button beside a field is the same shape as the field. A call site's own `size` wins.
  const shared = {
    size: '$4',
    rounded: '$5',
    fontWeight: '600',
    transition: 'quicker',
    /*
     * Only the press scale animates; the fill changes on the frame the finger lands. A tweened fill made
     * every press feel a beat late, and on a ghost button it tweened from `transparent` through dark. The same rule
     * as `IconButton` and `Chip`.
     */
    animateOnly: ['transform'] as string[],
    disabledStyle: { opacity: 0.5 },
    disabled: disabled || isLoading,
  } as const;

  const look =
    variant === 'primary'
      ? { bg: solid.bg, borderWidth: 0, pressStyle: { bg: solid.pressed, scale: PRESSED_SCALE }, fg: solid.label }
      : variant === 'destructive'
        ? { bg: '$background', borderWidth: 1, borderColor: '$color7', pressStyle: { bg: '$color3', scale: PRESSED_SCALE }, fg: theme.color11?.val }
        : variant === 'ghost'
          ? { bg: 'transparent', borderWidth: 0, pressStyle: { bg: '$color3', scale: PRESSED_SCALE }, fg: theme.color11?.val }
          : {
              bg: '$background',
              borderWidth: 1,
              // `$color5`, one step firmer than the card hairline: a secondary button sitting on a card must still
              // read as a control rather than as a second, smaller card.
              borderColor: '$color5',
              pressStyle: { bg: '$color3', borderColor: '$color6', scale: PRESSED_SCALE },
              fg: theme.color12?.val,
            };

  const { fg, ...surface } = look;

  return (
    <TamaguiButton
      {...shared}
      {...(surface as object)}
      // A resolved value is valid at runtime for both the text and the icon; the prop is typed for tokens only.
      color={fg as GetProps<typeof TamaguiButton>['color']}
      icon={isLoading ? <Spinner color={fg} /> : icon}
      {...props}
    >
      {children}
      {/* On Android a touch on the button's own view never reached its press handler; only one on the label or icon
          did, so the sides were dead. This transparent child covers the button, so
          every touch lands on a child. */}
      <View collapsable={false} style={StyleSheet.absoluteFill} />
    </TamaguiButton>
  );
}
